@dataclass(frozen=True)
class ScaleFixture:
    """One generated scale fixture and the pipeline coordinates it is measured on.

    Attributes:
        name: File name written into the output directory, and the fixture's key in
            the budget file and the benchmark report.
        paradigm: Canonical paradigm the fixture covers (see :data:`PARADIGMS`).
        adapter_key: ImportSource registry key the import half runs through.
        export_target: Emitter key the export half emits to. Chosen as the format's
            own emitter wherever one exists, so the measured export is the
            round-trip a user of that format would actually run.
        description: One line on what makes the fixture large.
        builder: Returns the fixture's bytes; deterministic and parameterless.
        approx_bytes: Rough on-disk size, for the suite's own budgeting.
        features: Corpus-style tags describing the fixture.
    """

    name: str
    paradigm: str
    adapter_key: str
    export_target: str
    description: str
    builder: Callable[[], bytes]
    approx_bytes: int = 0
    features: List[str] = field(default_factory=list)


