def build_fixture(fixture: ScaleFixture, out_dir: Path) -> Path:
    """Materialize one fixture into ``out_dir``.

    Args:
        fixture: The spec entry to build.
        out_dir: Directory to write into; created if absent.

    Returns:
        The path written.
    """
    out_dir.mkdir(parents=True, exist_ok=True)
    target = out_dir / fixture.name
    target.write_bytes(fixture.builder())
    return target


def write_all(out_dir: Path) -> List[Path]:
    """Materialize every fixture in :data:`SCALE_FIXTURES`.

    Args:
        out_dir: Directory to write into.

    Returns:
        The paths written, in spec order.
    """
    return [build_fixture(fixture, out_dir) for fixture in SCALE_FIXTURES]


def main(argv: Optional[List[str]] = None) -> int:
    """CLI entry point.

    Args:
        argv: Argument vector; defaults to ``sys.argv[1:]``.

    Returns:
        Process exit code.
    """
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out-dir", type=Path, help="Directory to write fixtures into.")
    parser.add_argument("--list", action="store_true", help="Print the spec and exit.")
    args = parser.parse_args(argv)

    if args.list or not args.out_dir:
        for fixture in SCALE_FIXTURES:
            print(
                f"{fixture.name:38s} {fixture.paradigm:12s} {fixture.adapter_key:14s} "
                f"-> {fixture.export_target:14s} {fixture.description}"
            )
        return 0

    for path in write_all(args.out_dir):
        print(f"wrote {path} ({os.stat(path).st_size} bytes)")
    return 0


if __name__ == "__main__":  # pragma: no cover - CLI
    sys.exit(main())
