def test_measure_records_time_and_allocation():
    """The primitive reports both metrics for the work it wraps."""
    # Distinct mutable buffers, not repeated literals: CPython folds ``"x" * 1024``
    # into one interned constant, so a list of them allocates almost nothing.
    payload, measurement = measure("parse", lambda: [bytearray(4096) for _ in range(512)])
    assert len(payload) == 512
    assert measurement.stage == "parse"
    assert measurement.wall_ms > 0
    assert measurement.peak_bytes > 1024 * 1024


def test_measure_stops_tracing_even_when_the_stage_raises():
    """A failing stage must not leave tracemalloc running for the next one."""
    import tracemalloc

    def _boom() -> None:
        raise RuntimeError("stage failed")

    with pytest.raises(RuntimeError, match="stage failed"):
        measure("parse", _boom)
    assert not tracemalloc.is_tracing()


def test_suite_is_opt_in(monkeypatch):
    """Without the flag or the variable, the scale suite does not run."""
    monkeypatch.delenv(ENABLE_ENV, raising=False)
    assert scale_suite_enabled(None) is False
    monkeypatch.setenv(ENABLE_ENV, "1")
    assert scale_suite_enabled(None) is True
