def test_committed_baseline_exists_and_is_canonically_formatted():
    """The baseline is committed in one place and stored in canonical form.

    Re-rendering the parsed document must reproduce the file byte for byte, so a
    refreshed baseline always lands as a numeric diff rather than a reformatting one.
    """
    assert BUDGETS_PATH.exists(), f"missing committed baseline: {BUDGETS_PATH}"
    text = BUDGETS_PATH.read_text(encoding="utf-8")
    assert render_budgets(json.loads(text)) == text, (
        f"{BUDGETS_PATH} is not canonically formatted; rewrite it with "
        "`pytest tests/test_scale_corpus.py --update-scale-budgets`"
    )


def test_committed_baseline_covers_exactly_the_spec():
    """Every spec fixture has a budget, and no budget outlives its fixture."""
    document = load_budgets()
    assert document["budget_version"] == BUDGET_VERSION
    budgeted = set(document["fixtures"])
    declared = {fixture.name for fixture in scale_fixtures()}
    assert budgeted == declared, (
        f"budgeted-but-undeclared: {sorted(budgeted - declared)}; "
        f"declared-but-unbudgeted: {sorted(declared - budgeted)}"
    )


def test_committed_baseline_budgets_every_stage_plausibly():
    """Every fixture budgets all ten stages with usable, in-ceiling numbers.

    A zero or missing budget can never fail, and a budget above the absolute ceiling
    would encode a broken pipeline as the accepted normal.
    """
    problems: List[str] = []
    for name, entry in load_budgets()["fixtures"].items():
        stages = entry.get("stages") or {}
        missing = sorted(set(STAGE_ORDER) - set(stages))
        if missing:
            problems.append(f"{name}: no budget for stage(s) {missing}")
        for stage, budget in stages.items():
            if budget["wall_ms"] <= 0:
                problems.append(f"{name}/{stage}: non-positive wall_ms budget")
            if budget["peak_bytes"] < 0:
                problems.append(f"{name}/{stage}: negative peak_bytes budget")
            if budget["wall_ms"] > ABSOLUTE_STAGE_SECONDS * 1000.0:
                problems.append(f"{name}/{stage}: wall budget is over the absolute ceiling")
            if budget["peak_bytes"] > ABSOLUTE_STAGE_PEAK_BYTES:
                problems.append(f"{name}/{stage}: peak budget is over the absolute ceiling")
    assert not problems, "committed baseline problems:\n  " + "\n  ".join(problems)


def test_committed_policy_can_actually_fail_a_build():
    """The margins and floors are set to values that still gate.

    A margin of 10x or a floor of a minute would leave the suite green through any
    regression; this pins the policy as a deliberate choice rather than a leftover.
    """
    document = load_budgets()
    assert 1.0 < document["regression_margin"] <= 3.0
    assert 1.0 < document["memory_margin"] <= 3.0
    assert 0 < document["wall_floor_ms"] <= 1000.0
    assert 0 < document["peak_floor_bytes"] <= 64 * 1024 * 1024


def test_baseline_records_the_machine_it_was_measured_on():
    """The baseline names its runtime, without which two runs are not comparable."""
    measured_on = load_budgets().get("measured_on") or {}
    assert measured_on.get("python"), "the baseline does not record its Python version"
    assert measured_on.get("platform"), "the baseline does not record its platform"


