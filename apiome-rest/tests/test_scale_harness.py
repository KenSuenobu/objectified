def test_report_carries_every_stage_with_its_budget_and_ratio():
    """The report pairs each measured stage with the budget it was held to."""
    measurements = [_measurement(wall_ms=1000.0, peak_bytes=1_000_000)]
    document = _budgets([_measurement(wall_ms=500.0, peak_bytes=500_000)])
    regressions, problems = compare(measurements, document)
    report = build_report(measurements, document, regressions, problems, [])

    [fixture] = report["fixtures"]
    assert tuple(fixture["stages"]) == STAGE_ORDER
    stage = fixture["stages"]["parse"]
    assert stage["budget"] == {"wall_ms": 500.0, "peak_bytes": 500_000}
    assert stage["wall_ratio"] == 2.0
    assert stage["peak_ratio"] == 2.0
    assert report["passed"] is False
    assert report["totals"]["fixtures"] == 1
    assert report["environment"]["python"]


def test_report_of_a_clean_run_passes():
    """A run inside its budgets reports ``passed`` with no findings."""
    measurements = [_measurement()]
    document = _budgets(measurements)
    regressions, problems = compare(measurements, document)
    report = build_report(measurements, document, regressions, problems, [])
    assert report["passed"] is True
    assert report["regressions"] == []
    assert report["problems"] == []
    assert report["breaches"] == []


def test_report_is_written_as_parseable_json(tmp_path):
    """The artifact round-trips through JSON, stages still in pipeline order."""
    measurements = [_measurement()]
    document = _budgets(measurements)
    report = build_report(measurements, document, [], [], [])
    written = write_report(report, tmp_path / "scale-report.json")
    reloaded = json.loads(written.read_text(encoding="utf-8"))
    assert reloaded == report
    assert tuple(reloaded["fixtures"][0]["stages"]) == STAGE_ORDER


def test_report_path_is_overridable(monkeypatch, tmp_path):
    """``SCALE_REPORT_PATH`` redirects the artifact; the default is under reports/."""
    monkeypatch.delenv(REPORT_PATH_ENV, raising=False)
    assert report_path() == default_report_path()
    assert default_report_path().parent.name == "reports"
    monkeypatch.setenv(REPORT_PATH_ENV, str(tmp_path / "elsewhere.json"))
    assert report_path() == tmp_path / "elsewhere.json"


