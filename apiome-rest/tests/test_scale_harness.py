def test_generator_script_is_committed():
    """The fixtures are generated by a committed script, keeping repo size flat."""
    assert GENERATOR_PATH.exists(), f"missing committed generator: {GENERATOR_PATH}"


def test_every_paradigm_is_covered_by_the_spec():
    """Every required paradigm has at least one scale fixture.

    The first acceptance criterion, asserted against the spec so it holds even in
    runs that do not take the measurements.
    """
    covered = {fixture.paradigm for fixture in scale_fixtures()}
    missing = sorted(set(scale_paradigms()) - covered)
    assert not missing, f"scale spec covers no fixture for paradigm(s): {missing}"


def test_spec_paradigms_use_the_corpus_vocabulary():
    """Paradigm labels match the corpus manifest's, not a private spelling.

    ``data_schema`` versus ``data-schema`` is exactly the kind of drift that makes
    two coverage reports disagree about the same gap.
    """
    known = {directory.paradigm for directory in load_manifest().directories.values()}
    unknown = sorted(set(scale_paradigms()) - known)
    assert not unknown, f"paradigms not in the corpus manifest vocabulary: {unknown}"
    for fixture in scale_fixtures():
        assert fixture.paradigm in scale_paradigms(), (
            f"{fixture.name}: paradigm {fixture.paradigm!r} is outside the declared set"
        )


def test_every_fixture_names_a_runnable_adapter_and_emitter():
    """Each fixture's adapter and emitter exist, and need no external toolchain.

    A tool-gated adapter (``buf`` for protobuf, ``asyncapi-parser`` for AsyncAPI)
    would make its fixture skip wherever the toolchain is absent, quietly dropping a
    paradigm from the tier. The scale spec therefore only uses adapters that run
    everywhere.
    """
    problems: List[str] = []
    for fixture in scale_fixtures():
        adapter = get_import_source(resolve_import_source_key(fixture.adapter_key))
        if adapter is None:
            problems.append(f"{fixture.name}: unknown adapter {fixture.adapter_key!r}")
        elif getattr(adapter, "required_tools", ()):
            problems.append(
                f"{fixture.name}: adapter {fixture.adapter_key!r} requires "
                f"{list(adapter.required_tools)}, so the fixture would skip"
            )
        if get_emitter(fixture.export_target) is None:
            problems.append(f"{fixture.name}: unknown emit target {fixture.export_target!r}")
    assert not problems, "scale spec problems:\n  " + "\n  ".join(problems)


def test_fixture_names_are_unique():
    """Fixture names key the budget file, so a duplicate would shadow a budget."""
    names = [fixture.name for fixture in scale_fixtures()]
    assert len(names) == len(set(names)), f"duplicate scale fixture names: {names}"


def test_builders_are_deterministic_and_correctly_sized():
    """Building a fixture twice yields identical bytes of the declared size.

    Determinism is what makes a regression reproducible from a fixture name alone,
    and the size assertion keeps ``approx_bytes`` — which the suite budgets against
    — honest as the builders are tuned.
    """
    for fixture in scale_fixtures():
        first = fixture.builder()
        second = fixture.builder()
        assert first == second, f"{fixture.name}: builder is not deterministic"
        assert len(first) < _MAX_DOCUMENT_BYTES, (
            f"{fixture.name}: {len(first)} bytes is over the intake ceiling, so the "
            "document would be rejected instead of measured"
        )
        assert 0.5 <= len(first) / fixture.approx_bytes <= 2.0, (
            f"{fixture.name}: built {len(first)} bytes against a declared "
            f"approx_bytes of {fixture.approx_bytes}"
        )


def test_write_all_materializes_every_fixture(tmp_path):
    """The generator writes one file per spec entry, named as the spec declares."""
    written = load_generator().write_all(tmp_path)
    assert [path.name for path in written] == [f.name for f in scale_fixtures()]
    for path in written:
        assert path.stat().st_size > 0, f"{path.name}: generator wrote an empty fixture"


