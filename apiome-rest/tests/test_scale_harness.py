#: The intake ceiling every scale fixture must stay under, so it is measured rather
#: than rejected (``app/data/oas_resource_limits.json`` ``maxDocumentBytes``).
_MAX_DOCUMENT_BYTES = 10 * 1024 * 1024


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------


def _measurement(
    name: str = "fixture.json",
    *,
    wall_ms: float = 100.0,
    peak_bytes: int = 1_000_000,
    paradigm: str = "rest",
) -> FixtureMeasurement:
    """Build a synthetic measurement with the same value on every stage.

    Args:
        name: Fixture name.
        wall_ms: Wall-clock recorded for every stage.
        peak_bytes: Peak allocation recorded for every stage.
        paradigm: Paradigm label.

    Returns:
        A :class:`FixtureMeasurement` covering every stage in :data:`STAGE_ORDER`.
    """
    return FixtureMeasurement(
        name=name,
        paradigm=paradigm,
        adapter_key="openapi",
        export_target="openapi-3.1",
        source_bytes=1_000,
        stages={
            stage: StageMeasurement(stage=stage, wall_ms=wall_ms, peak_bytes=peak_bytes)
            for stage in STAGE_ORDER
        },
        process_peak_rss_bytes=2_000_000,
        detail={"types": 1},
    )


def _budgets(measurements: List[FixtureMeasurement], **policy: Any) -> Dict[str, Any]:
    """Build a budget document from measurements with an optional policy override."""
    document = budgets_from_measurements(measurements)
    document.update(policy)
    return document


