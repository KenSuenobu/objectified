"""Contract tests for the scale benchmark harness — IXH-1.5 (#5091).

The measurements themselves are opt-in and scheduled (:mod:`tests.test_scale_corpus`
runs for a minute and allocates hundreds of megabytes), but the machinery around
them must not be allowed to rot between scheduled runs. This module runs on every
PR and covers the three things that make the gate trustworthy:

* the **generator spec** covers every paradigm, and every fixture names an adapter
  and an emitter that exist and are runnable without an external toolchain — a
  fixture that silently could not run would remove a paradigm from the tier;
* the **committed baseline** has an entry for exactly the spec's fixtures and all
  ten stages, with a policy (margins, floors) that could actually fail a build;
* the **comparison rules** behave: over the margin fails, under it passes, and
  sub-floor noise is suppressed rather than reported.

Everything here is cheap: the only real work is building the fixture documents,
which the spec keeps to a few megabytes in total.
"""

