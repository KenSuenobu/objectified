def test_a_run_matching_its_baseline_has_no_regressions():
    """The identity case: measurements equal to the budget pass."""
    measurements = [_measurement()]
    regressions, problems = compare(measurements, _budgets(measurements))
    assert regressions == []
    assert problems == []


def test_a_stage_over_the_margin_and_floor_is_a_regression():
    """A slow stage fails, and the failure names the fixture, stage, and ratio."""
    baseline = [_measurement(wall_ms=1000.0)]
    slower = [_measurement(wall_ms=2500.0)]
    regressions, problems = compare(slower, _budgets(baseline))
    assert problems == []
    assert {r.metric for r in regressions} == {"wall_ms"}
    assert len(regressions) == len(STAGE_ORDER)
    described = describe_regression(regressions[0])
    assert "fixture.json" in described and "2.50x" in described


def test_a_stage_under_the_margin_is_not_a_regression():
    """Drift the margin tolerates does not fail the build."""
    baseline = [_measurement(wall_ms=1000.0)]
    slightly_slower = [_measurement(wall_ms=1400.0)]
    regressions, _problems = compare(slightly_slower, _budgets(baseline))
    assert regressions == []


def test_sub_floor_noise_is_suppressed():
    """A fast stage that doubles is noise, not a regression.

    2 ms → 6 ms is a 3x ratio and utterly meaningless; without the absolute floor
    the suite would fail on scheduler jitter and be ignored within a week.
    """
    baseline = [_measurement(wall_ms=2.0, peak_bytes=1_000)]
    noisy = [_measurement(wall_ms=6.0, peak_bytes=5_000)]
    regressions, _problems = compare(noisy, _budgets(baseline))
    assert regressions == []


def test_memory_growth_is_gated_separately_from_time():
    """A stage that keeps its time but doubles its peak still fails."""
    baseline = [_measurement(peak_bytes=100 * 1024 * 1024)]
    hungry = [_measurement(peak_bytes=300 * 1024 * 1024)]
    regressions, _problems = compare(hungry, _budgets(baseline))
    assert {r.metric for r in regressions} == {"peak_bytes"}


def test_an_unbudgeted_fixture_is_a_problem_not_a_pass():
    """A fixture with no committed budget fails, with the refresh command in hand."""
    measurements = [_measurement(name="brand-new.json")]
    regressions, problems = compare(measurements, _budgets([_measurement(name="old.json")]))
    assert regressions == []
    assert any("brand-new.json" in problem for problem in problems)
    assert any("--update-scale-budgets" in problem for problem in problems)


def test_a_stale_budget_entry_is_a_problem():
    """A budget for a fixture the spec dropped is reported rather than ignored."""
    measurements = [_measurement(name="kept.json")]
    document = _budgets([_measurement(name="kept.json"), _measurement(name="dropped.json")])
    _regressions, problems = compare(measurements, document)
    assert any("dropped.json" in problem for problem in problems)


def test_a_stage_missing_from_a_budget_entry_is_a_problem():
    """A budget entry that lost a stage cannot silently stop gating it."""
    measurements = [_measurement()]
    document = _budgets(measurements)
    document["fixtures"]["fixture.json"]["stages"].pop("normalize")
    _regressions, problems = compare(measurements, document)
    assert any("'normalize'" in problem for problem in problems)


def test_margins_are_overridable_per_run(monkeypatch):
    """``SCALE_REGRESSION_MARGIN`` / ``SCALE_MEMORY_MARGIN`` win over the file."""
    document = _budgets([_measurement()], regression_margin=1.6, memory_margin=1.5)
    assert wall_margin(document) == 1.6
    monkeypatch.setenv(WALL_MARGIN_ENV, "2.5")
    monkeypatch.setenv(PEAK_MARGIN_ENV, "3.0")
    assert wall_margin(document) == 2.5
    assert peak_margin(document) == 3.0


def test_a_margin_below_one_is_rejected(monkeypatch):
    """A margin under 1.0 would fail every run; it is a typo, not a policy."""
    monkeypatch.setenv(WALL_MARGIN_ENV, "0.5")
    with pytest.raises(ValueError, match="multiplier"):
        wall_margin(_budgets([_measurement()]))


def test_absolute_ceilings_catch_a_breakage_without_any_baseline():
    """A hung or memory-hungry stage fails regardless of the committed numbers."""
    hung = [_measurement(wall_ms=ABSOLUTE_STAGE_SECONDS * 1000.0 + 1.0)]
    breaches = ceiling_breaches(hung)
    assert {breach.metric for breach in breaches} == {"wall_ms"}
    assert "absolute ceiling" in describe_breach(breaches[0])

    hungry = [_measurement(peak_bytes=ABSOLUTE_STAGE_PEAK_BYTES + 1)]
    assert {breach.metric for breach in ceiling_breaches(hungry)} == {"peak_bytes"}


def test_a_healthy_run_breaches_no_ceiling():
    """The ceilings do not fire on ordinary measurements."""
    assert ceiling_breaches([_measurement()]) == []


def test_default_policy_constants_are_consistent():
    """The fallback floors are positive, so a file without them still gates sanely."""
    assert DEFAULT_WALL_FLOOR_MS > 0
    assert DEFAULT_PEAK_FLOOR_BYTES > 0


